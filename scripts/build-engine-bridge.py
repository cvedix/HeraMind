#!/usr/bin/env python3
"""Build, test and package the HeraMind engine bridge without installing it."""
import argparse
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
EXTENSION = ROOT / "extensions/engine-bridge"


def run(*args, env=None):
    subprocess.run([str(arg) for arg in args], cwd=ROOT, env=env, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seetaface", action="store_true", help="Require prebuilt SeetaFace libraries")
    parser.add_argument("--runner", type=Path, help="Also verify the package through this HeraMind extension runner")
    parser.add_argument("--models-dir", type=Path, help="Bundle verified SeetaFace6 models from this directory (requires --seetaface)")
    parser.add_argument("--output", type=Path, default=ROOT / ".local/engine-bridge/engine-bridge.nep")
    args = parser.parse_args()
    if args.models_dir and not args.seetaface:
        parser.error("--models-dir requires --seetaface")
    if platform.machine() not in ("aarch64", "arm64"):
        parser.error("This package currently targets Linux ARM64; cross-build/package mapping is not configured")
    build = ROOT / ".local/engine-bridge-build"
    stage = ROOT / ".local/engine-bridge/package"
    run("cmake", "-S", EXTENSION / "native", "-B", build,
        "-DCMAKE_BUILD_TYPE=Release", f"-DHERAMIND_WITH_SEETAFACE={'ON' if args.seetaface else 'OFF'}")
    run("cmake", "--build", build, "-j", "4")
    test_env = {**os.environ, "HERAMIND_TEST_ENGINE_WORKER": str(build / "engine-worker")}
    run("python3", EXTENSION / "native/test_worker.py", env=test_env)
    run("cargo", "test", "--locked", "-p", "heramind-engine-bridge", "--", "--include-ignored", env=test_env)
    run("cargo", "build", "--locked", "--release", "-p", "heramind-engine-bridge")
    # The stage is exclusively generated by this command; keep models/state out of it.
    if stage.exists():
        shutil.rmtree(stage)
    (stage / "assets").mkdir(parents=True)
    (stage / "binaries/linux_arm64").mkdir(parents=True)
    shutil.copy2(EXTENSION / "manifest.json", stage / "manifest.json")
    shutil.copy2(EXTENSION / "README.vi.md", stage / "README.vi.md")
    shutil.copytree(EXTENSION / "frontend", stage / "frontend")
    shutil.copy2(ROOT / "thirdparty/engine/third_party/seetaface6/FaceRecognizer6/example/1.png",
        stage / "assets/seetaface-example.png")
    shutil.copy2(build / "engine-worker", stage / "assets/engine-worker")
    if args.seetaface:
        libraries = stage / "assets/lib"
        libraries.mkdir()
        for library in (ROOT / "thirdparty/engine/third_party/seetaface6/build/lib").glob("*.so*"):
            shutil.copy2(library, libraries / library.name)
    if args.models_dir:
        source_models = args.models_dir.resolve()
        provenance = json.loads((source_models / "provenance.json").read_text())
        required = {"face_detector.csta", "mask_detector.csta", "face_landmarker_pts5.csta",
            "face_recognizer.csta", "face_landmarker_mask_pts5.csta", "face_recognizer_mask.csta", "age_predictor.csta"}
        records = {record["name"]: record for record in provenance["models"]}
        if set(records) != required:
            raise SystemExit("Model provenance must contain the seven recognition/age models; rerun setup-seetaface-models.py")
        destination = stage / "models/seetaface6"
        destination.mkdir(parents=True)
        import hashlib
        for name in sorted(required):
            model = source_models / name
            with model.open("rb") as stream:
                digest = hashlib.file_digest(stream, "sha256").hexdigest()
            if digest != records[name]["sha256"]:
                raise SystemExit(f"Model checksum mismatch: {name}")
            shutil.copy2(model, destination / name)
        shutil.copy2(source_models / "provenance.json", destination / "provenance.json")
    shutil.copy2(ROOT / "target/release/libheramind_engine_bridge.so", stage / "binaries/linux_arm64/extension.so")
    # Preserve the submodule patch needed to reproduce this integration.
    patch = subprocess.check_output(["git", "-C", str(ROOT / "thirdparty/engine"), "diff", "--binary"])
    (stage / "engine.patch").write_bytes(patch)
    (stage / "build-info.json").write_text(json.dumps({
        "heramind_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "engine_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT / "thirdparty/engine", text=True).strip(),
        "seetaface_compiled": args.seetaface,
        "qnn_available": False,
    }, indent=2) + "\n")
    if args.runner:
        run("python3", ROOT / "scripts/tests/test_engine_bridge_runner.py", "--runner", args.runner.resolve(),
            "--extension-root", stage)
    if args.models_dir:
        run("python3", ROOT / "scripts/tests/test_engine_bridge_seetaface.py", "--extension-root", stage,
            "--fixture", ROOT / "thirdparty/engine/third_party/seetaface6/FaceRecognizer6/example/1.png",
            "--report", stage / "seetaface-validation.json")
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(stage.rglob("*")):
            if path.is_file():
                archive.write(path, path.relative_to(stage))
    print(f"Built and tested: {output}")


if __name__ == "__main__":
    main()
